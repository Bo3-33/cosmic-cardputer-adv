#!/usr/bin/env python3
"""Compile the user-provided Flipper raw IR capture without normalizing timings."""
from pathlib import Path
root = Path(__file__).resolve().parent.parent
source = root / 'assets/ir/Honeywell_Fan_HYF290B.ir'
records = []
for line in source.read_text().splitlines():
    if ':' not in line or line.lstrip().startswith('#'): continue
    key, value = (p.strip() for p in line.split(':', 1))
    if key == 'name': records.append({'name': value})
    elif records and key in {'type','frequency','duty_cycle','data'}: records[-1][key] = value
assert [r['name'] for r in records] == ['Power','Oscillate','Fan_Speed']
text = '// Generated by support_files/generate_honeywell_ir.py from the supplied raw capture.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\nnamespace honeywell {\n'
for index, record in enumerate(records):
    assert record['type'] == 'raw'
    data = [int(v) for v in record['data'].split()]
    assert data and all(0 < v < 32768 for v in data)
    assert int(record['frequency']) == 38000 and float(record['duty_cycle']) == .33
    text += f'inline constexpr uint16_t signal{index}[] = {{' + ','.join(map(str,data)) + '};\n'
    print(f"{record['name']}: {len(data)} durations, {sum(data)/1000:.1f} ms")
text += 'struct Signal { const char *name; const uint16_t *durations; size_t count; };\ninline constexpr Signal signals[] = {\n'
for index,record in enumerate(records):
    text += '{"' + record['name'].replace('_',' ') + f'", signal{index}, sizeof(signal{index})/sizeof(uint16_t)' + '},\n'
text += '};\ninline constexpr unsigned frequency = 38000;\ninline constexpr float duty = 0.33f;\n}\n'
(root/'src/honeywell_signals.h').write_text(text)
